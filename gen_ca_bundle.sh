#!/bin/sh
# Generate src/ca_bundle.h from the Mozilla CA bundle.
# Source of truth: https://curl.se/ca/cacert.pem
cd /tmp || exit 1
test -f cacert.pem || curl -sSL -o cacert.pem https://curl.se/ca/cacert.pem
test -f cacert.pem || exit 1

dst=/mnt/d/workspace/perdolinque/qwenmaxxing/anonfm_vsrat_reader_glmaya/src/ca_bundle.h
{
    echo "/*"
    echo " * ca_bundle.h -- Mozilla CA bundle, embedded in the binary."
    echo " *"
    echo " * Generated from https://curl.se/ca/cacert.pem. Renew it from time"
    echo " * to time with gen_ca_bundle.sh. Do not edit this file by hand."
    echo " */"
    echo ""
    echo "#ifndef AFR_CA_BUNDLE_H"
    echo "#define AFR_CA_BUNDLE_H"
    echo ""
    echo "static const char afr_ca_bundle[] ="
    cat cacert.pem \
        | sed 's/\r$//' \
        | sed 's/"/\\"/g' \
        | awk '{ printf "\"" $0 "\\n\"\n" }'
    echo ";"
    echo ""
    echo "#endif"
} > "$dst"
echo "ca_bundle.h generated: $(wc -l < "$dst") lines"
